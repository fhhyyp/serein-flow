using Serein.Generator.Framework;
using Microsoft.CodeAnalysis;
using SereinFlow.Mcp.Generator.Models;

namespace SereinFlow.Mcp.Generator.Extensions;

internal static class McpHostExtension
{
    internal static readonly DiagnosticDescriptor InvalidHost = new DiagnosticDescriptor(
        "MCPGEN004", "Invalid MCP host declaration MCP 宿主声明无效。", "Host '{0}': {1}", "McpGeneration", DiagnosticSeverity.Error, true);

    internal static string GenerateCode(this McpHostCache cache, GenerationContext context)
    {
        var generator = new CodeBuilder<McpHostCache>(context, cache);
        generator.AppendCode("// <auto-generated/>").AppendCode("#nullable enable");
        if (cache.Namespace.Length > 0) generator.AppendCode($"namespace {cache.Namespace};");
        generator.AppendCode($"{cache.Accessibility} static partial class @{cache.ClassName}");
        generator.AppendCodeBlock(() => generator
            .GeneratorRegistration()
            .GeneratorCatalog()
            .GeneratorHooks());
        return generator.ToCode();
    }

    private static CodeBuilder<McpHostCache> GeneratorRegistration(this CodeBuilder<McpHostCache> generator)
    {
        var method = generator.Cache.RegistrationMethodName;
        generator.AppendCode($"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection @{method}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        generator.AppendCode($"    => @{method}(services, new {generator.Cache.RegistryTypeName}());");
        generator.AppendCode($"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection @{method}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::SereinFlow.Mcp.Framework.IMcpToolRegistry registry, params global::System.Type[] toolTypes)");
        return generator.AppendCodeBlock(() =>
        {
            generator.AppendCode("ConfigureServices(services);");
            generator.AppendCode("return global::SereinFlow.Mcp.Framework.McpToolDiscovery.AddMcpToolHandlers(services, registry, toolTypes);");
        });
    }

    private static CodeBuilder<McpHostCache> GeneratorCatalog(this CodeBuilder<McpHostCache> generator)
    {
        generator.AppendCode("public static global::SereinFlow.Mcp.Framework.McpToolCatalog CreateCatalog(global::System.Collections.Generic.IReadOnlyList<global::SereinFlow.Mcp.Framework.McpToolDescriptor>? contracts = null)");
        generator.AppendCode($"    => CreateCatalog(new {generator.Cache.RegistryTypeName}(), contracts: contracts);");
        generator.AppendCode("public static global::SereinFlow.Mcp.Framework.McpToolCatalog CreateCatalog(global::SereinFlow.Mcp.Framework.IMcpToolRegistry registry, global::System.Collections.Generic.IEnumerable<global::System.Type>? toolTypes = null, global::System.Collections.Generic.IReadOnlyList<global::SereinFlow.Mcp.Framework.McpToolDescriptor>? contracts = null)");
        return generator.AppendCodeBlock(() =>
        {
            generator.AppendCode("var jsonOptions = new global::SereinFlow.Mcp.Framework.McpToolDiscoveryOptions().JsonOptions;");
            generator.AppendCode("ConfigureJsonOptions(ref jsonOptions);");
            generator.AppendCode("var options = new global::SereinFlow.Mcp.Framework.McpToolDiscoveryOptions { JsonOptions = jsonOptions };");
            generator.AppendCode("var catalog = global::SereinFlow.Mcp.Framework.McpToolDiscovery.CreateCatalog(registry, contracts, options, toolTypes);");
            generator.AppendCode("ConfigureCatalog(catalog);");
            generator.AppendCode("return catalog;");
        });
    }

    private static void GeneratorHooks(this CodeBuilder<McpHostCache> generator)
    {
        generator.AppendCode("static partial void ConfigureServices(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services);");
        generator.AppendCode("static partial void ConfigureJsonOptions(ref global::System.Text.Json.JsonSerializerOptions options);");
        generator.AppendCode("static partial void ConfigureCatalog(global::SereinFlow.Mcp.Framework.McpToolCatalog catalog);");
    }
}
