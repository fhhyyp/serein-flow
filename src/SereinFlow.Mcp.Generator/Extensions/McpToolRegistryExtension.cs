using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using SereinFlow.Mcp.Generator.Models;

namespace SereinFlow.Mcp.Generator.Extensions;

/// <summary>根据工具缓存模型生成目录、DI 工厂和直接调用代码。</summary>
internal static class McpToolRegistryExtension
{
    private static readonly DiagnosticDescriptor Duplicate = new DiagnosticDescriptor(
        "MCPGEN001", "Duplicate MCP tool", "Tool name '{0}' is declared more than once", "McpGeneration", DiagnosticSeverity.Error, true);

    internal static string GenerateCode(this McpToolRegistryCache cache, SourceProductionContext context)
    {
        var tools = cache.GetValidTools(context);
        var generator = new GeneratorCache<McpToolRegistryCache>(context, cache, new StringBuilder());
        return generator.GeneratorHeader().GeneratorRegistry(tools).ToCode();
    }

    private static IReadOnlyList<McpToolCache> GetValidTools(this McpToolRegistryCache cache, SourceProductionContext context)
    {
        var tools = new List<McpToolCache>();
        foreach (var group in cache.Tools.GroupBy(tool => tool.Name, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (group.Count() > 1)
            {
                foreach (var duplicate in group)
                    context.ReportDiagnostic(Diagnostic.Create(Duplicate, duplicate.Location, duplicate.Name));
                continue;
            }
            var tool = group.Single();
            foreach (var diagnostic in tool.Diagnostics) context.ReportDiagnostic(diagnostic);
            if (tool.Diagnostics.Count == 0) tools.Add(tool);
        }
        return tools;
    }

    private static GeneratorCache<McpToolRegistryCache> GeneratorHeader(this GeneratorCache<McpToolRegistryCache> generator)
    {
        var generatedNamespace = string.Join(".", generator.Cache.AssemblyName.Split('.').Select(name => "@" + name));
        return generator.AppendCode("// <auto-generated/>")
            .AppendCode("#nullable enable")
            .AppendCode($"namespace {generatedNamespace}.Generated;");
    }

    private static GeneratorCache<McpToolRegistryCache> GeneratorRegistry(this GeneratorCache<McpToolRegistryCache> generator, IReadOnlyList<McpToolCache> tools)
    {
        generator.AppendCode("public sealed class McpToolRegistry : global::SereinFlow.Mcp.Framework.IMcpToolRegistry");
        return generator.AppendCodeBlok(() =>
        {
            generator.AppendCode("public global::System.Collections.Generic.IReadOnlyList<global::SereinFlow.Mcp.Framework.McpGeneratedTool> Tools => Entries;");
            generator.AppendCode("private static readonly global::System.Collections.Generic.IReadOnlyList<global::SereinFlow.Mcp.Framework.McpGeneratedTool> Entries =");
            generator.AppendCode("global::System.Array.AsReadOnly(new global::SereinFlow.Mcp.Framework.McpGeneratedTool[]");
            generator.AppendCodeBlok(() => generator.AppendCode(tools, tool => generator.GeneratorTool(tool)));
            generator.AppendCode(");");
            generator.GeneratorValidations();
            generator.GeneratorPropertyBindings();
        });
    }

    private static void GeneratorTool(this GeneratorCache<McpToolRegistryCache> generator, McpToolCache tool)
    {
        generator.AppendCode("new global::SereinFlow.Mcp.Framework.McpGeneratedTool(");
        generator.AppendTab(() =>
        {
            var requestType = tool.RequestTypeName is null ? "null" : $"typeof({tool.RequestTypeName})";
            generator.AppendCode($"typeof({tool.HandlerTypeName}), {requestType},");
            generator.AppendCode(tool.MetadataExpression + ",");
            generator.GeneratorHandlerFactory(tool).GeneratorInvocation(tool);
            if (tool.BindingMethodName is null) generator.AppendCode("),");
            else
            {
                var binding = generator.Cache.Validations.Single(item => item.BindingMethodName == tool.BindingMethodName);
                var required = string.Join(", ", binding.Bindings.Where(property => property.Required).Select(property => property.WireNameExpression));
                generator.AppendCode(")");
                generator.AppendCode($"{{ RequiredProperties = static options => new string[] {{ {required} }} }},");
            }
        });
    }

    private static GeneratorCache<McpToolRegistryCache> GeneratorHandlerFactory(this GeneratorCache<McpToolRegistryCache> generator, McpToolCache tool)
    {
        if (tool.IsStatic) return generator.AppendCode("static services => { },");
        return generator.AppendCode($"static services => global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<{tool.HandlerTypeName}>(services,")
            .AppendCode($"    static provider => new {tool.HandlerTypeName}({tool.ConstructorArguments})),");
    }

    private static void GeneratorInvocation(this GeneratorCache<McpToolRegistryCache> generator, McpToolCache tool)
    {
        generator.AppendCode("static async (context, arguments, options, cancellationToken) =>");
        generator.AppendCodeBlok(() =>
        {
            if (tool.RequestTypeName is not null)
            {
                generator.AppendCode(tool.BindingMethodName is not null
                    ? $"var request = {tool.BindingMethodName}(global::SereinFlow.Mcp.Framework.McpRequestBinder.Normalize(arguments), options);"
                    : $"var request = global::SereinFlow.Mcp.Framework.McpRequestBinder.Bind<{tool.RequestTypeName}>(context, arguments, options, {tool.ValidationMethodName});");
            }
            if (!tool.IsStatic)
                generator.AppendCode($"var handler = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{tool.HandlerTypeName}>(context.Services);");
            var owner = tool.IsStatic ? tool.HandlerTypeName : "handler";
            generator.AppendCode($"return (object?)await {owner}.{tool.MethodName}({tool.InvocationArguments}).ConfigureAwait(false);");
        });
    }
}
